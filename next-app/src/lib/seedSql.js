// Writes the demo seed and reset SQL from lib/seedRows.js. Node only (uses node:crypto).
// Run `npm run seed:build` after changing crew.json or standtests.json; seedSql.test.js fails
// if the committed supabase/seed.sql or supabase/reset_demo.sql is out of date.

import { createHash } from 'node:crypto';
import { seedAll } from './seedRows.js';

/** Stable UUID (version-5 layout, SHA-1) for a seed row key, so re-running the seed never duplicates. */
export function seedUuid(key) {
  const h = createHash('sha1').update(`ahm-seed/v1:${key}`).digest('hex');
  const variant = ((parseInt(h[16], 16) & 0x3) | 0x8).toString(16);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${variant}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

const HEADER = `-- GENERATED by scripts/build-seed.mjs from src/data/crew.json and src/data/standtests.json.
-- Do not edit by hand: run \`npm run seed:build\`. lib/seedSql.test.js checks this file is current.
-- Synthetic data for a fictional crew. Not real astronaut records. PhysioNet nights are not crew data
-- and are not stored here.`;

/** The seed statements (no transaction wrapper). Safe to run more than once. */
export function seedStatements(crewFile, standFile) {
  const { crew, baselines, readings } = seedAll(crewFile, standFile);
  const crewRows = crew
    .map((c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.role)}, ${q(c.mission)}, ${q(c.title)}, ${q(c.launch_date)})`)
    .join(',\n');
  const baselineRows = baselines.map((b) => `  (${q(b.crew_id)}, ${q(b.kind)}, ${j(b.payload)}, ${q(b.source)})`).join(',\n');
  const readingRows = readings
    .map(
      (r) =>
        `  (${q(seedUuid(r.key))}, ${q(r.crew_id)}, ${q(r.kind)}, ${q(r.recorded_at)}, ${j(r.payload)}, ${q(r.status)}, ${j(r.reasons)}, ${q(r.engine_version)})`,
    )
    .join(',\n');

  return `-- ${crew.length} crew members (crew-03 is the Crew Medical Officer)
insert into public.crew_members (id, name, role, mission, title, launch_date) values
${crewRows}
on conflict (id) do update set
  name = excluded.name, role = excluded.role, mission = excluded.mission,
  title = excluded.title, launch_date = excluded.launch_date;

-- ${baselines.length} preflight baselines (mean of each person's preflight list)
insert into public.baselines (crew_id, kind, payload, source) values
${baselineRows}
on conflict (crew_id, kind) do update set payload = excluded.payload, source = excluded.source;

-- ${readings.length} seeded readings (in-flight daily vitals + preflight stand tests); append-only, so do nothing on conflict
insert into public.readings (id, crew_id, kind, recorded_at, payload, status, reasons, engine_version) values
${readingRows}
on conflict (id) do nothing;
`;
}

export function buildSeedSql(crewFile, standFile) {
  return `${HEADER}

begin;

${seedStatements(crewFile, standFile)}
commit;
`;
}

export function buildResetSql(crewFile, standFile) {
  return `${HEADER}
--
-- DEMO RESET: removes every reading that was not seeded (everything synced from devices), clears the
-- access log and the emergency records, then re-runs the seed. Runs in one transaction: if anything
-- fails, nothing changes and the append-only trigger stays on. Crew accounts and their links
-- (crew_members.user_id) are kept.

begin;

alter table public.readings disable trigger readings_append_only;
delete from public.readings where payload->>'origin' is distinct from 'seed';
alter table public.readings enable trigger readings_append_only;

-- access_log is append-only (its trigger rejects UPDATE and DELETE). TRUNCATE does not fire that
-- row trigger: this demo reset script is the only place the append-only rule is bypassed.
-- Each table is skipped if its migration has not been run yet.
do $$
begin
  if to_regclass('public.access_log') is not null then
    truncate table public.access_log;
  end if;
  if to_regclass('public.emergency_events') is not null then
    truncate table public.emergency_events;
  end if;
end;
$$;

${seedStatements(crewFile, standFile)}
commit;
`;
}
